struct Volume {
    width: usize,  // x axis
    height: usize, // y axis
    depth: usize,  // z axis

    voxels: Vec<f32>,
}

struct Mesh {
    vertices: Vec<(f32, f32, f32)>,
    indices: Vec<u32>,
}

impl Mesh {
    fn new() -> Mesh {
        Mesh { 
            vertices: Vec::new(), 
            indices: Vec::new() 
        }
    }
}

fn vertex_interpolation(
    pos_a: (usize, usize, usize),
    pos_b: (usize, usize, usize),
    factor: f32,
) -> (f32, f32, f32) {
    let v_difference = (
        (pos_b.0 - pos_a.0) as f32 * factor,
        (pos_b.1 - pos_a.1) as f32 * factor,
        (pos_b.2 - pos_a.2) as f32 * factor,
    );

    (
        pos_a.0 as f32 + v_difference.0,
        pos_a.1 as f32 + v_difference.1,
        pos_a.2 as f32 + v_difference.2,
    )
}

fn extract_mesh(volume: &Volume, iso_value: f32) -> Mesh {
    let mut mesh = Mesh::new();

    let y_stride = volume.width;
    let z_stride = volume.width * volume.height;

    for z in 0..volume.depth - 1 {
        let z_offset = z * z_stride;
        for y in 0..volume.height - 1 {
            let y_offset = z_offset + y * y_stride;
            for x in 0..volume.width - 1 {
                let i0 = x + y_offset;
                let i1 = i0 + 1;
                let i2 = i0 + 1 + y_stride;
                let i3 = i0 + y_stride;
                let i4 = i0 + z_stride;
                let i5 = i1 + z_stride;
                let i6 = i2 + z_stride;
                let i7 = i3 + z_stride;

                let mut cube_index = 0;
                if volume.voxels[i0] < iso_value {
                    cube_index |= 1;
                }
                if volume.voxels[i1] < iso_value {
                    cube_index |= 2;
                }
                if volume.voxels[i2] < iso_value {
                    cube_index |= 4;
                }
                if volume.voxels[i3] < iso_value {
                    cube_index |= 8;
                }
                if volume.voxels[i4] < iso_value {
                    cube_index |= 16;
                }
                if volume.voxels[i5] < iso_value {
                    cube_index |= 32;
                }
                if volume.voxels[i6] < iso_value {
                    cube_index |= 64;
                }
                if volume.voxels[i7] < iso_value {
                    cube_index |= 128;
                }

                let intersected_edges = EDGE_TABLE[cube_index];
                if intersected_edges == 0 {
                    continue;
                }

                let mut edge_points = [None; 12];
                if intersected_edges & 1 != 0 {
                    let factor = divide(
                        iso_value - volume.voxels[i0],
                        volume.voxels[i1] - volume.voxels[i0],
                    )
                    .unwrap_or(0.5);
                    let pos_a = (x, y, z);
                    let pos_b = (x + 1, y, z);
                    edge_points[0] = Some(vertex_interpolation(pos_a, pos_b, factor));
                }
                if intersected_edges & 2 != 0 {
                    let factor = divide(
                        iso_value - volume.voxels[i1],
                        volume.voxels[i2] - volume.voxels[i1],
                    )
                    .unwrap_or(0.5);
                    let pos_a = (x + 1, y, z);
                    let pos_b = (x + 1, y + 1, z);
                    edge_points[1] = Some(vertex_interpolation(pos_a, pos_b, factor));
                }
                if intersected_edges & 4 != 0 {
                    let factor = divide(
                        iso_value - volume.voxels[i2],
                        volume.voxels[i3] - volume.voxels[i2],
                    )
                    .unwrap_or(0.5);
                    let pos_a = (x + 1, y + 1, z);
                    let pos_b = (x, y + 1, z);
                    edge_points[2] = Some(vertex_interpolation(pos_a, pos_b, factor));
                }
                if intersected_edges & 8 != 0 {
                    let factor = divide(
                        iso_value - volume.voxels[i3],
                        volume.voxels[i0] - volume.voxels[i3],
                    )
                    .unwrap_or(0.5);
                    let pos_a = (x, y + 1, z);
                    let pos_b = (x, y, z);
                    edge_points[3] = Some(vertex_interpolation(pos_a, pos_b, factor));
                }
                if intersected_edges & 16 != 0 {
                    let factor = divide(
                        iso_value - volume.voxels[i4],
                        volume.voxels[i5] - volume.voxels[i4],
                    )
                    .unwrap_or(0.5);
                    let pos_a = (x, y, z + 1);
                    let pos_b = (x + 1, y, z + 1);
                    edge_points[4] = Some(vertex_interpolation(pos_a, pos_b, factor));
                }
                if intersected_edges & 32 != 0 {
                    let factor = divide(
                        iso_value - volume.voxels[i5],
                        volume.voxels[i6] - volume.voxels[i5],
                    )
                    .unwrap_or(0.5);
                    let pos_a = (x + 1, y, z + 1);
                    let pos_b = (x + 1, y + 1, z + 1);
                    edge_points[5] = Some(vertex_interpolation(pos_a, pos_b, factor));
                }
                if intersected_edges & 64 != 0 {
                    let factor = divide(
                        iso_value - volume.voxels[i6],
                        volume.voxels[i7] - volume.voxels[i6],
                    )
                    .unwrap_or(0.5);
                    let pos_a = (x + 1, y + 1, z + 1);
                    let pos_b = (x, y + 1, z + 1);
                    edge_points[6] = Some(vertex_interpolation(pos_a, pos_b, factor));
                }
                if intersected_edges & 128 != 0 {
                    let factor = divide(
                        iso_value - volume.voxels[i7],
                        volume.voxels[i4] - volume.voxels[i7],
                    )
                    .unwrap_or(0.5);
                    let pos_a = (x, y + 1, z + 1);
                    let pos_b = (x, y, z + 1);
                    edge_points[7] = Some(vertex_interpolation(pos_a, pos_b, factor));
                }
                if intersected_edges & 256 != 0 {
                    let factor = divide(
                        iso_value - volume.voxels[i0],
                        volume.voxels[i4] - volume.voxels[i0],
                    )
                    .unwrap_or(0.5);
                    let pos_a = (x, y, z);
                    let pos_b = (x, y, z + 1);
                    edge_points[8] = Some(vertex_interpolation(pos_a, pos_b, factor));
                }
                if intersected_edges & 512 != 0 {
                    let factor = divide(
                        iso_value - volume.voxels[i1],
                        volume.voxels[i5] - volume.voxels[i1],
                    )
                    .unwrap_or(0.5);
                    let pos_a = (x + 1, y, z);
                    let pos_b = (x + 1, y, z + 1);
                    edge_points[9] = Some(vertex_interpolation(pos_a, pos_b, factor));
                }
                if intersected_edges & 1024 != 0 {
                    let factor = divide(
                        iso_value - volume.voxels[i2],
                        volume.voxels[i6] - volume.voxels[i2],
                    )
                    .unwrap_or(0.5);
                    let pos_a = (x + 1, y + 1, z);
                    let pos_b = (x + 1, y + 1, z + 1);
                    edge_points[10] = Some(vertex_interpolation(pos_a, pos_b, factor));
                }
                if intersected_edges & 2048 != 0 {
                    let factor = divide(
                        iso_value - volume.voxels[i3],
                        volume.voxels[i7] - volume.voxels[i3],
                    )
                    .unwrap_or(0.5);
                    let pos_a = (x, y + 1, z);
                    let pos_b = (x, y + 1, z + 1);
                    edge_points[11] = Some(vertex_interpolation(pos_a, pos_b, factor));
                }

                let triangles = TRI_TABLE[cube_index];
                for i in triangles {
                    if i == -1 {
                        break;
                    }
                    mesh.vertices.push(edge_points[i as usize].unwrap());
                    mesh.indices.push((mesh.vertices.len() - 1) as u32);
                }
            }
        }
    }

    mesh
}

